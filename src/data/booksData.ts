export interface BookData {
  id: string;
  title: string;
  volume: string;
  year?: number;
  description: string;
  fullDescription: string;
  quote: string;
  quoteAuthor: string;
  cover: string;
}

/* ---------- Утилы ---------- */

export function getPrevNext(currentId: string): { prev: BookData | null; next: BookData | null } {
  const idx = books.findIndex((b) => b.id === currentId);
  if (idx === -1) return { prev: null, next: null };
  const prev = idx > 0 ? books[idx - 1] : null;
  const next = idx < books.length - 1 ? books[idx + 1] : null;
  return { prev, next };
}

/* Поиск по всем книгам (по названию, описанию или полному тексту) */
export function filterBooks(query: string): BookData[] {
  const q = query.trim().toLowerCase();
  if (!q) return books;
  return books.filter(
    (b) =>
      b.title.toLowerCase().includes(q) ||
      b.description.toLowerCase().includes(q) ||
      b.fullDescription.toLowerCase().includes(q),
  );
}

